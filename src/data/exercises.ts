export function getExercisesForModule(moduleId: string): Exercise[] {
  return exercises.filter((exercise) => exercise.moduleId === moduleId);
}

export function getExercisesByDifficulty(
  moduleId: string,
  difficulty: Difficulty,
): Exercise[] {
  return exercises.filter(
    (exercise) => exercise.moduleId === moduleId && exercise.difficulty === difficulty,
  );
}

export function getExerciseById(id: string): Exercise | undefined {
  return exercises.find((exercise) => exercise.id === id);
}
